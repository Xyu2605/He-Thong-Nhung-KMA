int main(void)
{
    HAL_Init();
    SystemClock_Config();

    MX_GPIO_Init();
    MX_I2C1_Init();
    MX_SPI1_Init();
    MX_TIM3_Init();
    MX_USART2_UART_Init();


    HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_4);
    Door_Close();
    Buzzer_Off();
    Password_LoadFlash();

    RFID_Init();

    CLCD_I2C_Init(&LCD1, &hi2c1, 0x4E, 16, 2);
    CLCD_I2C_Clear(&LCD1);
    app_state = ST_LOGIN;
    LCD_ShowInput("Nhap mat khau");


    while (1)
    {
        /* Module 1: keypad */
        char key = Keypad_Scan();
        if (key != 0)
        {
            printf("[KEY] '%c'\r\n", key);
            HandleKey(key);

            while (Keypad_Scan() != 0) HAL_Delay(10);
            HAL_Delay(20);
        }

        /* Module 4: RFID — chỉ khi login */
        if (app_state == ST_LOGIN)
        {
            if (RFID_PollAdmin())
            {
                printf("[RFID] The ADMIN!\r\n");
                ClearInput();
                app_state = ST_ADMIN_OLD_PASSWORD;
                LCD_ShowInput("MK hien tai:");
            }
        }

        /* Module 2: timer */
        CheckSystemTimers();

        /* USER CODE END WHILE */
    }
    /* USER CODE END 3 */
}


